"""
CAD Engineering & SolidWorks Automated Modeling Tools
Supports:
1. 2D Standard Industrial CAD Drafting (.dxf generation via ezdxf)
2. 3D SolidWorks Parametric VBA Macro Script Generation (.bas/.swp)
"""

import os
import math
from typing import Dict, Any

DESKTOP_PATH = os.path.join(os.path.expanduser("~"), "Desktop")

def draw_cad_part(part_type: str, params: Dict[str, Any], filename: str = None) -> str:
    """
    Generate professional 2D mechanical CAD drawing (.dxf) and save to Desktop.
    :param part_type: 'flange', 'shaft', or 'plate'
    :param params: dimensional parameters (e.g. {'outer_diameter': 120, 'inner_diameter': 35})
    :param filename: output filename (e.g. 'flange_part.dxf')
    """
    try:
        import ezdxf
    except ImportError:
        return "Error: ezdxf library is required. Install via `pip install ezdxf`."

    part_type = part_type.lower()
    if not filename:
        filename = f"{part_type}_drawing.dxf"
    if not filename.lower().endswith(".dxf"):
        filename += ".dxf"
        
    output_path = os.path.join(DESKTOP_PATH, filename)
    doc = ezdxf.new(dxfversion="R2010")
    msp = doc.modelspace()

    # Define CAD standard layers
    doc.layers.new(name="OUTLINE", dxfattribs={"color": 7})       # White/Black solid
    doc.layers.new(name="CENTERLINE", dxfattribs={"color": 1})    # Red centerlines
    doc.layers.new(name="HOLES", dxfattribs={"color": 3})         # Green hole lines
    doc.layers.new(name="TEXT", dxfattribs={"color": 2})          # Yellow annotations

    if "flange" in part_type:
        d_outer = float(params.get("outer_diameter", 120))
        d_inner = float(params.get("inner_diameter", 30))
        pcd = float(params.get("pcd", 80))
        num_holes = int(params.get("num_holes", 4))
        hole_d = float(params.get("bolt_hole_diameter", 10))

        # Outer & Inner Circles
        msp.add_circle((0, 0), radius=d_outer / 2, dxfattribs={"layer": "OUTLINE"})
        msp.add_circle((0, 0), radius=d_inner / 2, dxfattribs={"layer": "OUTLINE"})
        msp.add_circle((0, 0), radius=pcd / 2, dxfattribs={"layer": "CENTERLINE"})

        # Bolt Holes
        for i in range(num_holes):
            angle = (2 * math.pi / num_holes) * i
            hx = (pcd / 2) * math.cos(angle)
            hy = (pcd / 2) * math.sin(angle)
            msp.add_circle((hx, hy), radius=hole_d / 2, dxfattribs={"layer": "HOLES"})

        # Center axes
        ext = d_outer / 2 + 15
        msp.add_line((-ext, 0), (ext, 0), dxfattribs={"layer": "CENTERLINE"})
        msp.add_line((0, -ext), (0, ext), dxfattribs={"layer": "CENTERLINE"})
        msp.add_text(f"Flange OD:{d_outer} ID:{d_inner} PCD:{pcd}", dxfattribs={"layer": "TEXT", "height": 3.5}).set_placement((-d_outer/2, -d_outer/2 - 20))

    elif "plate" in part_type:
        length = float(params.get("length", 150))
        width = float(params.get("width", 100))
        margin = float(params.get("hole_margin", 15))
        hole_d = float(params.get("hole_diameter", 8))

        points = [(0, 0), (length, 0), (length, width), (0, width), (0, 0)]
        msp.add_lwpolyline(points, dxfattribs={"layer": "OUTLINE"})

        hole_coords = [
            (margin, margin),
            (length - margin, margin),
            (length - margin, width - margin),
            (margin, width - margin)
        ]
        for hx, hy in hole_coords:
            msp.add_circle((hx, hy), radius=hole_d / 2, dxfattribs={"layer": "HOLES"})
        msp.add_text(f"Plate {length}x{width}mm", dxfattribs={"layer": "TEXT", "height": 3.5}).set_placement((0, -15))

    doc.saveas(output_path)
    return f"CAD drawing successfully generated and saved to Desktop: '{output_path}'"

def generate_solidworks_macro(part_name: str, part_type: str, params: Dict[str, Any], filename: str = None) -> str:
    """
    Generate SolidWorks VBA Macro Script (.bas) for automated 3D parametric modeling.
    """
    if not filename:
        filename = f"{part_name}_3D_Macro.bas"
    if not filename.lower().endswith((".bas", ".swp")):
        filename += ".bas"
        
    output_path = os.path.join(DESKTOP_PATH, filename)
    d_out = float(params.get("outer_diameter", 120)) / 1000.0
    d_in = float(params.get("inner_diameter", 30)) / 1000.0
    thk = float(params.get("thickness", 15)) / 1000.0
    pcd = float(params.get("pcd", 80)) / 1000.0
    h_d = float(params.get("bolt_hole_diameter", 10)) / 1000.0

    vba_code = f"""' ==============================================================
' SolidWorks VBA Macro: Parametric 3D Modeling Automation
' Generated by WeChat-Silent-Agent
' Part: {part_name}
' ==============================================================

Dim swApp As Object
Dim Part As Object
Dim boolstatus As Boolean
Dim longstatus As Long

Sub main()
    Set swApp = Application.SldWorks
    Set Part = swApp.NewDocument("Part.prtdot", 0, 0, 0)
    If Part Is Nothing Then Set Part = swApp.ActiveDoc

    ' 1. Select Front Plane & Create Sketch
    boolstatus = Part.Extension.SelectByID2("Front Plane", "PLANE", 0, 0, 0, False, 0, Nothing, 0)
    Part.SketchManager.InsertSketch True
    Part.ClearSelection2 True

    ' 2. Draw Concentric Circles (OD and ID)
    Part.SketchManager.CreateCircleByRadius 0, 0, 0, {d_out / 2}
    Part.SketchManager.CreateCircleByRadius 0, 0, 0, {d_in / 2}

    ' 3. Base Extrude Feature
    Part.FeatureManager.FeatureExtrusion2 True, False, False, 0, 0, {thk}, 0, False, False, False, False, 0, 0, False, False, False, False, True, True, True, 0, 0, False
    Part.ClearSelection2 True

    ' 4. Bolt Hole Sketch on Extruded Face
    boolstatus = Part.Extension.SelectByID2("", "FACE", 0, 0, {thk}, False, 0, Nothing, 0)
    Part.SketchManager.InsertSketch True

    ' 4 Bolt Holes on PCD
    Part.SketchManager.CreateCircleByRadius {pcd / 2}, 0, 0, {h_d / 2}
    Part.SketchManager.CreateCircleByRadius -{pcd / 2}, 0, 0, {h_d / 2}
    Part.SketchManager.CreateCircleByRadius 0, {pcd / 2}, 0, {h_d / 2}
    Part.SketchManager.CreateCircleByRadius 0, -{pcd / 2}, 0, {h_d / 2}

    ' 5. Extruded Cut for Through Holes
    Part.FeatureManager.FeatureCut4 True, False, False, 1, 0, {thk}, 0, False, False, False, False, 0, 0, False, False, False, False, False, True, True, True, True, False, 0, 0, False, False

    Part.ViewZoomtofit2
    MsgBox "{part_name} 3D modeling finished!", vbInformation, "SolidWorks Automation"
End Sub
"""
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(vba_code)
        
    return f"SolidWorks 3D automation macro successfully generated: '{output_path}'"
